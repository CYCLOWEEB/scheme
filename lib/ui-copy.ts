export function tr(language: string, text: string): string {
  if (language !== 'hi') return text;
  return (PROFILE_HI[text] ?? HI[text] ?? AI_HI[text] ?? translateDynamicHindi(text))
    .replace(/\bLakh\b/g, 'लाख')
    .replace(/\blakh\b/g, 'लाख')
    .replace(/\bCrore\b/g, 'करोड़')
    .replace(/\bcrore\b/g, 'करोड़');
}

