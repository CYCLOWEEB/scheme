export function localizeScheme(scheme: Scheme, language: string): Scheme {
  if (language !== 'hi') return scheme;
  return {
    ...scheme,
    name: `${scheme.hindiName} (${scheme.code})`,
    hindiName: scheme.name,
    categoryTag: tr(language, scheme.categoryTag),
    interestRateNote: scheme.interestRateNote ? tr(language, scheme.interestRateNote) : undefined,
    repaymentTerms: scheme.repaymentTerms ? tr(language, scheme.repaymentTerms) : undefined,
    moratoriumTerms: scheme.moratoriumTerms ? tr(language, scheme.moratoriumTerms) : undefined,
    availabilityNote: scheme.availabilityNote ? tr(language, scheme.availabilityNote) : undefined,
    overview: tr(language, scheme.overview),
    keyBenefits: scheme.keyBenefits.map(item => tr(language, item)),
    mandatoryDocuments: scheme.mandatoryDocuments.map(item => tr(language, item)),
    eligibilityBullets: scheme.eligibilityBullets.map(item => tr(language, item)),
    financialHighlights: scheme.financialHighlights?.map(item => ({ ...item, label: tr(language, item.label), value: tr(language, item.value), note: item.note ? tr(language, item.note) : undefined })),
  };
}

export function formatLocalizedINR(value: number, language: string): string {
  if (language !== 'hi') return value >= 10000000
    ? `₹${(value / 10000000).toFixed(2)} Cr`
    : value >= 100000
      ? `₹${(value / 100000).toFixed(2)} Lakh`
      : `₹${value.toLocaleString('en-IN')}`;
  if (value >= 10000000) return `₹${(value / 10000000).toFixed(2)} करोड़`;
  if (value >= 100000) return `₹${(value / 100000).toFixed(2)} लाख`;
  return `₹${value.toLocaleString('en-IN')}`;
}
